export function auditActionLabel(action: string): string {
  const known = actionLabels[action];
  if (known) return known;
  const text = action
    .split(/[._]/)
    .filter(Boolean)
    .map((w) => words[w] ?? w)
    .reverse()
    .join(' ');
  return text ? text[0]!.toUpperCase() + text.slice(1) : action;
}

